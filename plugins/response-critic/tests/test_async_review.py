def critic(monkeypatch):
    spec = importlib.util.spec_from_file_location('response_critic_regression', PLUGIN / '__init__.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    monkeypatch.setattr(module, '_ensure_logging', lambda: None)
    monkeypatch.setattr(module, '_conversation_from_frames', lambda: [])
    monkeypatch.setattr(module, '_background_pending', lambda sid: False)
    return module


def internal_turn(c, sid='s', prior=ANSWER):
    if prior:
        c.record_completed_answer(session_id=sid, assistant_response=prior)
    c.observe_gateway_input(event=SimpleNamespace(internal=True, text=NOTICE))
    return c.capture_turn_context(session_id=sid, user_message=NOTICE)


