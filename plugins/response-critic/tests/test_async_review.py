PLUGIN = Path(__file__).resolve().parents[1]
NOTICE = '[ASYNC DELEGATION BATCH COMPLETE — regression-test]\nResearch finished.\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]'
ANSWER = 'The completed answer contains verified results and the final recommendation.'
HANDOFF = 'Background research is still running; I am waiting for the results.'

