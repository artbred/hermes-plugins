def test_plugin_loads_via_real_manager_in_isolated_home(tmp_path, monkeypatch):
    home = tmp_path / 'home'; directory = home / 'plugins' / 'response-critic'
    directory.mkdir(parents=True)
    for name in ['__init__.py', 'plugin.yaml']:
        shutil.copy2(PLUGIN / name, directory / name)
    (home / 'config.yaml').write_text('plugins:\n  enabled: [response-critic]\n  entries:\n    response-critic:\n      allow_tool_override: false\n')
    monkeypatch.setenv('HERMES_HOME', str(home))
    from hermes_cli.plugins import PluginManager
    manager = PluginManager(scope_key=str(home))
    manager.discover_and_load()
    expected = {'pre_gateway_dispatch', 'pre_llm_call', 'post_llm_call', 'transform_llm_output', 'pre_api_request', 'pre_verify'}
    assert expected <= set(manager._hooks)
    manager.invoke_hook('post_llm_call', session_id='s', assistant_response=ANSWER)
    manager.invoke_hook('pre_gateway_dispatch', event=SimpleNamespace(internal=True, text=NOTICE))
    manager.invoke_hook('pre_llm_call', session_id='s', user_message=NOTICE, conversation_history=[])
    assert 'NO_REPLY' in manager.invoke_hook('transform_llm_output', response_text=ANSWER, session_id='s', turn_id='test-turn')


def test_mid_turn_user_steering_overrides_initial_request(critic, monkeypatch):
    critic.capture_turn_context(session_id='s', user_message='Explain publisher payouts and KYC.')
    steer = '[OUT-OF-BAND USER MESSAGE — a direct message from the user]\nFix the verification plugin, not the core.\n[/OUT-OF-BAND USER MESSAGE]'
    monkeypatch.setattr(critic, '_conversation_from_frames', lambda: [
        {'role': 'user', 'content': 'Explain publisher payouts and KYC.'},
        {'role': 'user', 'content': steer},
        {'role': 'user', 'content': 'Repeat the old task.', '_pre_verify_hook_continue': True},
    ])
    evidence = critic._evidence_appendix(session_id='s')
    assert 'Fix the verification plugin' in evidence
    assert 'Explain publisher payouts' not in evidence
    assert 'Repeat the old task' not in evidence


